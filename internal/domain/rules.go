// IsParty: is actor the renter, the provider, or (role "any") either of them?
func IsParty(b *Booking, actor ID, role string) bool {
	switch role {
	case "renter":
		return b.RenterID == actor
	case "provider":
		return b.ProviderID == actor
	}
	return b.RenterID == actor || b.ProviderID == actor
}

// Counterpart returns the other party of a booking.
func Counterpart(b *Booking, actor ID) ID {
	if actor == b.RenterID {
		return b.ProviderID
	}
	return b.RenterID
}

func BookingHref(b *Booking) string { return "/sewaan/" + b.ID }

func Contains(xs []string, v string) bool {
	for _, x := range xs {
		if x == v {
			return true
		}
	}
	return false
}

var idPattern = regexp.MustCompile(`^[a-z]{1,4}-[a-z0-9]{6,32}$`)

// PickID accepts the id generated by the client (so optimistic UI and navigation stay consistent) when it is
// well-formed, has the right prefix and is unused; otherwise a fresh id is generated.
func PickID(want, prefix string, exists func(ID) bool) ID {
	if want != "" && idPattern.MatchString(want) && strings.HasPrefix(want, prefix+"-") && !exists(want) {
		return want
	}
	return NewID(prefix)
}

// NormListing guarantees non-nil slices so the JSON never contains null where the web app expects arrays.
func NormListing(l *Listing) {
	if l.Photos == nil {
		l.Photos = []string{}
	}
	if l.CollateralOptions == nil {
		l.CollateralOptions = []CollateralOption{}
	}
	if l.Handover == nil {
		l.Handover = []string{}
	}
}

// Normalize guarantees non-nil slices/maps across a dataset.
func Normalize(d *Data) {
	if d.Favorites == nil {
		d.Favorites = map[ID][]ID{}
	}
	if d.ChatReads == nil {
		d.ChatReads = map[string]int64{}
	}
	if d.ListingBusy == nil {
		d.ListingBusy = map[ID][]BusyRange{}
	}
	if d.BannedKeywords == nil {
		d.BannedKeywords = []string{}
	}
	for _, l := range d.Listings {
		NormListing(l)
	}
	for _, b := range d.Bookings {
		if b.Agreement.ReferencePhotos == nil {
			b.Agreement.ReferencePhotos = []string{}
		}
	}
	for _, x := range d.Disputes {
		if x.Proposals == nil {
			x.Proposals = []DisputeProposal{}
		}
		if x.PhotoIDs == nil {
			x.PhotoIDs = []ID{}
		}
	}
	for _, w := range d.Wanted {
		if w.Offers == nil {
			w.Offers = []WantedOffer{}
		}
	}
	nonNil(&d.Users)
	nonNil(&d.Verifications)
	nonNil(&d.Listings)
	nonNil(&d.Bookings)
	nonNil(&d.Photos)
	nonNil(&d.Messages)
	nonNil(&d.Reviews)
	nonNil(&d.Reports)
	nonNil(&d.Disputes)
	nonNil(&d.Strikes)
	nonNil(&d.Audit)
	nonNil(&d.Wanted)
	nonNil(&d.Notifications)
}

func nonNil[T any](s *[]T) {
	if *s == nil {
		*s = []T{}
	}
}

// CanTransact: renting and lending need an active, verified account (FR-A6).
func CanTransact(u *User) error {
	if u == nil {
		return Fail("Akun tidak ditemukan.")
	}
	if u.Status != "aktif" {
		if u.Status == "suspend" {
			return Fail("Akun sedang ditangguhkan.")
		}
		return Fail("Akun sedang diblokir.")
	}
	if u.Verification.Status != "terverifikasi" {
		return Fail("Verifikasi KTP + selfie dulu sebelum menyewa atau menyewakan.")
	}
	return nil
}

var nonDigits = regexp.MustCompile(`\D`)

// Digits keeps only 0-9 (phone numbers and NIK are stored as digits, like v1).
func Digits(s string) string { return nonDigits.ReplaceAllString(s, "") }
